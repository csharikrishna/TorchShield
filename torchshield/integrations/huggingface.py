def save_hf_model(
    model: nn.Module,
    output_path: str,
    key: Union[bytes, KeyProvider],
    chunk_bytes: int = 4 * 1024 * 1024,
) -> None:
    """Save weights of a Hugging Face PreTrainedModel into an encrypted AEAD container."""
    key_bytes = key if isinstance(key, bytes) else None
    key_provider = key if isinstance(key, KeyProvider) else None
    SecureModelCheckpoint.save_checkpoint(
        state_dict=model.state_dict(),
        output_path=output_path,
        key=key_bytes,
        key_provider=key_provider,
        chunk_bytes=chunk_bytes,
    )


def load_hf_model(
    model: nn.Module,
    input_path: str,
    key: Union[bytes, KeyProvider],
    device: Union[str, torch.device] = "cpu",
) -> nn.Module:
    """Load weights into a Hugging Face PreTrainedModel from an encrypted AEAD container."""
    key_bytes = key if isinstance(key, bytes) else None
    key_provider = key if isinstance(key, KeyProvider) else None
    loaded_state = SecureModelCheckpoint.load_checkpoint(
        input_path=input_path,
        key=key_bytes,
        key_provider=key_provider,
        device=device,
    )
    model.load_state_dict(loaded_state)
    return model
